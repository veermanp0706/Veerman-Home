let TAAL = "nl";
try { TAAL = localStorage.getItem("taal") === "en" ? "en" : "nl"; } catch (e) { /* geen opslag */ }

/** Tekst ophalen in de gekozen taal en {velden} invullen. */
function t(sleutel, velden) {
  let s = (TEKSTEN[TAAL] && TEKSTEN[TAAL][sleutel]) ?? TEKSTEN.nl[sleutel] ?? sleutel;
  if (velden) s = s.replace(/\{(\w+)\}/g, (_, k) => (velden[k] ?? ""));
  return s;
}

/** Locale voor getallen en datums. */
function locale() { return TAAL === "en" ? "en-GB" : "nl-NL"; }

/** Alle vaste teksten in de pagina vertalen. */
function vertaalPagina() {
  document.documentElement.lang = TAAL;
  document.querySelectorAll("[data-t]").forEach((el) => { el.textContent = t(el.dataset.t); });
  document.querySelectorAll("[data-t-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.tAria)); });
}
